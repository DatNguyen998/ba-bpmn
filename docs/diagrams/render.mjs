// Renders every *.mmd next to this file into <name>.light.svg and <name>.dark.svg with Pele (https://pele.run).
// Development tool only: nothing here ships to users. Run it with:  npm ci && npm run render
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { render } from 'pele';

const here = dirname(fileURLToPath(import.meta.url));

// Pele writes every colour as var(--pele-name, fallback). A standalone picture has no page to set those variables,
// so each theme is made by choosing the fallback values.
const LIGHT = null;                       // Pele's own light defaults
const DARK = {                            // GitHub's dark theme colours
  '--pele-bg': '#0d1117', '--pele-fg': '#e6edf3', '--pele-muted': '#9198a1', '--pele-line': '#8b949e',
  '--pele-surface': '#161b22', '--pele-surface-alt': '#21262d', '--pele-border': '#3d444d', '--pele-accent': '#4493f8',
};

function theme(svg, palette) {
  if (!palette) return svg;
  return svg.replace(/var\((--pele-[a-z0-9-]+),\s*([^)]+)\)/g, (all, name, fallback) =>
    name in palette ? `var(${name}, ${palette[name]})` : all);
}

for (const file of readdirSync(here).filter(f => f.endsWith('.mmd')).sort()) {
  const name = file.slice(0, -4);
  const source = readFileSync(join(here, file), 'utf8').replace(/\r\n/g, '\n');
  const digest = createHash('sha256').update(source, 'utf8').digest('hex');
  const { svg, width, height } = render(source, { fontFamily: 'Arial, "Liberation Sans", Helvetica, sans-serif' });
  for (const [label, palette] of [['light', LIGHT], ['dark', DARK]]) {
    const out = `<!-- Generated by render.mjs with Pele from ${file}. Do not edit. source-sha256: ${digest} -->\n` +
      theme(svg, palette) + '\n';
    writeFileSync(join(here, `${name}.${label}.svg`), out, 'utf8');
  }
  console.log(`${name}: ${width}x${height}, light and dark written`);
}
