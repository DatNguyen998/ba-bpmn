"""The instruction files, the traps list and the public-repository rules."""
import hashlib
import re
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).parent.parent
SKIP_DIRS = {".git", "__pycache__", ".pytest_cache", "node_modules"}
SKIP_FILES = {"bpmn-viewer.development.js", "test_docs.py"}      # third-party file; this file names the banned terms


def candidate_files():
    """The files that would be published: everything Git would add, so ignored build output is left out."""
    try:
        out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"], cwd=ROOT,
                             capture_output=True, text=True, check=True, encoding="utf-8").stdout
        return [ROOT / line for line in out.splitlines() if line]
    except (OSError, subprocess.CalledProcessError):
        return [p for p in ROOT.rglob("*") if p.is_file()]


def text_files():
    for path in candidate_files():
        if path.is_file() and not (set(path.parts) & SKIP_DIRS) and path.name not in SKIP_FILES \
                and path.suffix in {".md", ".py", ".json", ".toml", ".txt", ".svg", ".mmd", ".mjs", ""}:
            yield path


def test_claude_md_only_imports_agents_md():
    assert (ROOT / "CLAUDE.md").read_text(encoding="utf-8") == "@AGENTS.md\n"


def test_agents_md_stays_short():
    lines = (ROOT / "AGENTS.md").read_text(encoding="utf-8").splitlines()
    assert 10 < len(lines) <= 120, "keep the instruction file short (Anthropic suggests well under 200 lines)"


def test_agents_md_points_at_the_traps_list_and_the_sync_script():
    text = (ROOT / "AGENTS.md").read_text(encoding="utf-8")
    assert "docs/TRAPS.md" in text and "scripts/sync_plugins.py" in text


def test_files_named_in_agents_md_exist():
    text = (ROOT / "AGENTS.md").read_text(encoding="utf-8")
    names = set(re.findall(r"`([\w./-]+\.(?:md|py|json|js|toml))`", text))
    assert names, "expected the file to name some files"
    for name in names:
        if "/" in name:
            assert (ROOT / name).exists(), name
        else:
            assert any(p.name == name for p in ROOT.rglob(name) if not (set(p.parts) & SKIP_DIRS)), name


DIAGRAMS = ROOT / "docs" / "diagrams"


def mmd_files():
    return sorted(DIAGRAMS.glob("*.mmd"))


def source_hash(path):
    return hashlib.sha256(path.read_text(encoding="utf-8").replace("\r\n", "\n").encode("utf-8")).hexdigest()


def test_readme_explains_how_it_works_with_pictures_in_light_and_dark():
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    assert "## How it works" in readme and "<picture>" in readme
    names = [p.stem for p in mmd_files()]
    assert len(names) >= 2, "one diagram of what a BA sees and one of what is inside"
    for name in names:
        for theme in ("light", "dark"):
            assert f"docs/diagrams/{name}.{theme}.svg" in readme, f"README does not show {name} ({theme})"
        assert f"docs/diagrams/{name}.mmd" in readme, f"README does not link the source of {name}"
    assert len(re.findall(r'<img alt="[^"]{40,}"', readme)) >= len(names), "every picture needs real alt text"


def test_every_diagram_source_has_fresh_light_and_dark_pictures():
    """The pictures are generated by Pele (docs/diagrams/render.mjs). A stale one means: run npm run render."""
    for mmd in mmd_files():
        digest = source_hash(mmd)
        for theme in ("light", "dark"):
            svg = DIAGRAMS / f"{mmd.stem}.{theme}.svg"
            assert svg.exists(), f"{svg.name} is missing: run npm run render in docs/diagrams"
            assert f"source-sha256: {digest}" in svg.read_text(encoding="utf-8"), f"{svg.name} is stale"


def test_diagram_pictures_are_valid_and_inert():
    pictures = sorted(DIAGRAMS.glob("*.svg"))
    assert pictures
    for svg in pictures:
        text = svg.read_text(encoding="utf-8")
        ET.fromstring(text)                                         # a browser stops at the first XML error
        body = text.replace("http://www.w3.org/2000/svg", "")
        for bad in ("<script", "onload=", "onclick=", "onerror=", "foreignobject", "javascript:", "http:", "https:"):
            assert bad not in body.lower(), f"{svg.name} contains {bad}"
    for mmd in mmd_files():
        light = (DIAGRAMS / f"{mmd.stem}.light.svg").read_text(encoding="utf-8")
        dark = (DIAGRAMS / f"{mmd.stem}.dark.svg").read_text(encoding="utf-8")
        assert light != dark, f"{mmd.stem}: the dark picture is the same as the light one"


def test_diagram_sources_avoid_characters_that_break_mermaid():
    """A semicolon ends a statement and a hash starts a comment in Mermaid."""
    for mmd in mmd_files():
        source = mmd.read_text(encoding="utf-8")
        assert ";" not in source and "#" not in source, mmd.name
        assert source.count("subgraph") == len(re.findall(r"^\s*end\s*$", source, re.M)), "unbalanced subgraph/end"


def test_public_text_has_no_internal_notes():
    """README, host READMEs and skills are read by strangers: no caveats in headings, no diary phrases."""
    public = [ROOT / "README.md", ROOT / "plugins" / "codex" / "ba-bpmn" / "README.md",
              ROOT / "plugins" / "antigravity" / "README.md", *sorted((ROOT / "skills").glob("*/SKILL.md"))]
    diary = ["original `bpmn-diagram`", "bpmn-diagram` skill", "tested here", "built here", "available here",
             "before going public", "learned from real reviews", "where this was built"]
    for path in public:
        text = path.read_text(encoding="utf-8")
        for heading in re.findall(r"^#{1,4} .*$", text, re.M):
            assert "(" not in heading or heading.startswith("# "), f"{path.name}: caveat in heading: {heading}"
        for phrase in diary:
            assert phrase not in text.lower(), f"{path.relative_to(ROOT)}: internal note: {phrase!r}"


def test_traps_are_numbered_without_gaps_and_complete():
    text = (ROOT / "docs" / "TRAPS.md").read_text(encoding="utf-8")
    numbers = [int(n) for n in re.findall(r"^## Trap (\d+):", text, re.M)]
    assert numbers == list(range(1, len(numbers) + 1)) and numbers
    for block in re.split(r"^## Trap \d+:.*$", text, flags=re.M)[1:]:
        for field in ("**Symptom:**", "**Cause:**", "**Fix lives in:**", "**Status:**"):
            assert field in block, field


def test_no_client_or_personal_terms_in_the_public_repository():
    banned = re.compile("|".join(["CI" + "MB", "DS" + "ME", "sme" + "-flow", "flexi" + "pay", "net" + "reveal",
                                  "red" + "E2e", "Bit" + "bucket", r"C:\\Users\\", r"/Users/\w"]), re.I)
    for path in text_files():
        hit = banned.search(path.read_text(encoding="utf-8", errors="ignore"))
        assert not hit, f"{path.relative_to(ROOT)}: {hit.group(0)}"


def test_no_secret_shaped_strings():
    secret = re.compile(r"ghp_[A-Za-z0-9]{20,}|github_pat_\w{20,}|sk-[A-Za-z0-9]{20,}|-----BEGIN [A-Z ]*PRIVATE KEY")
    for path in text_files():
        assert not secret.search(path.read_text(encoding="utf-8", errors="ignore")), path.name
